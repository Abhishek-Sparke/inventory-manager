# https://docs.djangoproject.com/en/6.1/ref/settings/#databases

def get_database_config(env=None):
    """
    Builds the database configuration dictionary from environment variables.
    Supports:
      1. Single DATABASE_URL (e.g. Supabase connection string)
      2. Discrete environment variables (DB_ENGINE, DB_HOST, DB_PORT, DB_NAME, DB_USER, DB_PASSWORD, DB_SSLMODE)
      3. Fallback to local MySQL for local development if PostgreSQL is not specified
    """
    if env is None:
        env = os.environ

    database_url = env.get("DATABASE_URL", "").strip()
    db_engine_env = env.get("DB_ENGINE", "").strip().lower()

    try:
        conn_max_age = int(env.get("DB_CONN_MAX_AGE", "0"))
    except ValueError:
        conn_max_age = 0

    if database_url:
        parsed_db_url = urlparse(database_url)
        url_scheme = parsed_db_url.scheme.lower()

        if url_scheme in ("postgres", "postgresql"):
            db_engine = "django.db.backends.postgresql"
            db_default_port = "5432"
        elif url_scheme == "mysql":
            db_engine = "django.db.backends.mysql"
            db_default_port = "3306"
        else:
            db_engine = url_scheme
            db_default_port = ""

        name = unquote(parsed_db_url.path.lstrip("/"))
        user = unquote(parsed_db_url.username or "")
        password = unquote(parsed_db_url.password or "")
        host = parsed_db_url.hostname or ""
        port = str(parsed_db_url.port) if parsed_db_url.port else db_default_port

        options = {}
        query_params = parse_qs(parsed_db_url.query)
        if "sslmode" in query_params:
            options["sslmode"] = query_params["sslmode"][0]
        elif "postgresql" in db_engine and ("supabase.co" in host or "pooler.supabase.com" in host):
            options["sslmode"] = "require"
        elif "mysql" in db_engine:
            options["charset"] = "utf8mb4"

        return {
            "ENGINE": db_engine,
            "NAME": name,
            "USER": user,
            "PASSWORD": password,
            "HOST": host,
            "PORT": port,
            "CONN_MAX_AGE": conn_max_age,
            "OPTIONS": options,
        }

    # Resolve database engine from DB_ENGINE environment variable.
    # Default fallback is MySQL for local development.
    if db_engine_env in ("postgresql", "postgres", "django.db.backends.postgresql"):
        db_engine = "django.db.backends.postgresql"
    elif db_engine_env in ("mysql", "django.db.backends.mysql"):
        db_engine = "django.db.backends.mysql"
    elif db_engine_env:
        db_engine = db_engine_env
    else:
        db_engine = "django.db.backends.mysql"

    options = {}
    if "postgresql" in db_engine:
        host = env.get("SUPABASE_HOST") or env.get("POSTGRES_HOST") or env.get("DB_HOST", "")
        port = env.get("SUPABASE_PORT") or env.get("POSTGRES_PORT") or env.get("DB_PORT", "5432")
        name = env.get("SUPABASE_NAME") or env.get("POSTGRES_NAME") or env.get("DB_NAME", "postgres")
        user = env.get("SUPABASE_USER") or env.get("POSTGRES_USER") or env.get("DB_USER", "postgres")
        password = env.get("SUPABASE_PASSWORD") or env.get("POSTGRES_PASSWORD") or env.get("DB_PASSWORD", "")
        sslmode = env.get("SUPABASE_SSLMODE") or env.get("POSTGRES_SSLMODE") or env.get("DB_SSLMODE", "require" if ("supabase.co" in host or "pooler.supabase.com" in host) else "")
        if sslmode:
            options["sslmode"] = sslmode
    else:
        host = env.get("MYSQL_HOST") or env.get("DB_HOST", "localhost")
        port = env.get("MYSQL_PORT") or env.get("DB_PORT", "3306")
        name = env.get("MYSQL_NAME") or env.get("DB_NAME", "")
        user = env.get("MYSQL_USER") or env.get("DB_USER", "")
        password = env.get("MYSQL_PASSWORD") or env.get("DB_PASSWORD", "")
        options["charset"] = "utf8mb4"

    return {
        "ENGINE": db_engine,
        "NAME": name,
        "USER": user,
        "PASSWORD": password,
        "HOST": host,
        "PORT": port,
        "CONN_MAX_AGE": conn_max_age,
        "OPTIONS": options,
    }


